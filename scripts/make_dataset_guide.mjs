#!/usr/bin/env node
// Writes docs/DATASET_COLLECTION.md from docs/dataset/shot_list.csv, so the guide's tables always match the CSV.
//   node scripts/make_shot_list.mjs && node scripts/make_dataset_guide.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lines = readFileSync(path.join(root, 'docs/dataset/shot_list.csv'), 'utf8').trim().split('\n').slice(1);
const parse = (l) => {
  const m = [];
  let cur = '';
  let q = false;
  for (const ch of l) {
    if (ch === '"') q = !q;
    else if (ch === ',' && !q) {
      m.push(cur);
      cur = '';
    } else cur += ch;
  }
  m.push(cur);
  return m;
};
const rows = lines.map(parse);

const tables = {};
for (const r of rows) {
  if (r[2] !== 'single' || r[5] !== '1') continue;
  const set = r[8] === 'top' && r[9] === 'near' ? 1 : 2;
  (tables[r[3]] ??= []).push(`| ${r[4]} | ${r[6]} | ${set} | ${r[10]} | ${r[11]} | ${r[14]} |`);
}
const classTable = (c) => `| Object | Location | Set | Condition | Item | Split |\n|---|---|---|---|---|---|\n${tables[c].join('\n')}`;

// Boxes per class across single, mixed and pile photos.
const boxes = {};
for (const r of rows) {
  if (r[2] === 'single') boxes[r[3]] = (boxes[r[3]] ?? 0) + 1;
  else if (r[2] === 'mixed' || r[2] === 'pile') for (const c of r[1].replace('.jpg', '').split('_')[3].split('-')) boxes[c] = (boxes[c] ?? 0) + 1;
}
const perClass = Object.entries(boxes).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([c, n]) => `${c} ${n}`).join(', ');
const total = rows.reduce((n, r) => n + Number(r[13]), 0);
const count = (t) => rows.filter((r) => r[2] === t).length;
const boxesOf = (t) => rows.filter((r) => r[2] === t).reduce((n, r) => n + Number(r[13]), 0);

const doc = `# Dataset collection guide

How to collect and label your own photos for the waste detector. The goal is a small, well-planned set: **${rows.length} photos, about ${total} labelled items**, built so that every material is shot in different places, angles and distances. The exact list of photos is in [dataset/shot_list.csv](./dataset/shot_list.csv); this guide explains how to use it. Both are generated by \`scripts/make_shot_list.mjs\` and \`scripts/make_dataset_guide.mjs\`, so change the tables in the first script and run both again. For how the photos are used afterwards, see [MODEL_LIFECYCLE.md](./MODEL_LIFECYCLE.md).

## 1. What you will collect

| Photo type | Photos | Labelled items |
|---|---|---|
| Single item: plastic 36, paper 30, cardboard 30, metal 36, glass 36, trash 30, biological 24 | ${count('single')} | ${boxesOf('single')} |
| Mixed: 2 to 4 items on a table or the floor | ${count('mixed')} | ${boxesOf('mixed')} |
| Pile: 5 to 7 items in a bag, bin or on the floor | ${count('pile')} | ${boxesOf('pile')} |
| Empty: no waste in the picture | ${count('none')} | 0 |
| **Total** | **${rows.length}** | **${total}** |

Labelled items per class (single, mixed and pile photos together): ${perClass}. This is enough to see a change in a fine-tuned model, not a large one; a second round of about 150 photos with new objects would bring it to roughly 700 items. Variety matters more than count: 12 different bottles teach more than 40 photos of one bottle.

## 2. Safety, hygiene and privacy

- No broken glass, sharp edges, batteries, bulbs, electronics, medicines or chemicals. Batteries, bulbs and e-waste are declared by hand in the app, not detected, so they are not labels.
- Wear gloves for food scraps, photograph them quickly and throw them away afterwards.
- No faces, number plates, addresses or personal text in the picture. Turn items so labels with personal details face away.
- Keep the photos in \`ml/data/\` (ignored by Git). Never commit them.

## 3. Camera setup

Use the phone you normally use for SnapPick, portrait orientation, normal camera mode, no flash, no digital zoom. Keep the item near the centre, because the app centre-crops to 384 px before detection.

| Term | Meaning |
|---|---|
| \`near\` | about 30 cm away; the item fills about half the picture |
| \`far\` | about 80 cm away; the item fills about a quarter of the picture |
| \`top\` | phone flat, camera pointing straight down at the item |
| \`side\` | phone at the item's height, camera pointing horizontally |
| \`45\` | camera pointing down at about 45 degrees |

| Location | Lighting | How |
|---|---|---|
| \`table\` | lamp | on a table or counter under a lamp or ceiling light |
| \`floor\` | window | on the floor near a window with daylight |
| \`bin\` | dim | lying inside an open bin or bag; no extra light |
| \`outdoor\` | daylight | on the ground, grass or pavement outside |

## 4. File names and folders

\`<class>_<object>_<shot>_<location>-<angle>-<distance>.jpg\`

- Single item: \`plastic_o01_s1_table-top-near.jpg\`, \`plastic_o01_s2_table-side-far.jpg\`, \`plastic_o01_s3_table-45-near.jpg\`. \`o01\` is one physical object; \`s1\` to \`s3\` are its three shots.
- Mixed: \`mixed_m001_table-45-near_plastic-metal.jpg\` (the materials in the picture are at the end).
- Pile: \`pile_p001_bin-top-near_plastic-metal-glass-paper-cardboard.jpg\`.
- Empty: \`none_n001_table-top-far.jpg\`.

The class in the file name is used later by the automatic labelling step, so spell it exactly: \`plastic\`, \`paper\`, \`cardboard\`, \`metal\`, \`glass\`, \`trash\`, \`biological\`. Put all photos in \`ml/data/photos/raw/\`, and copy \`docs/dataset/shot_list.csv\` to \`ml/data/shot_list.csv\` to tick off your own copy (the \`done\` and \`notes\` columns).

## 5. The shot rotation

Every object is photographed **3 times**, once from each angle. Which distances you use depends on the set:

| Set | Shot 1 | Shot 2 | Shot 3 |
|---|---|---|---|
| 1 | top, near | side, far | 45, near |
| 2 | top, far | side, near | 45, far |

Objects 1 to 4 use set 1 in table, floor, bin, outdoor. Objects 5 to 8 use set 2 in the same four places. Objects 9 to 12 use set 1 again. So every location, angle and distance is covered evenly. Every object also has a condition (clean, dirty, wet, crushed, fresh or dry) in the tables below, about a third dirty or wet and a quarter crushed. The CSV has one row per photo with all of this filled in.

## 6. Objects, one table per class

Set and location follow the rotation above. Split is explained in section 8.

### Plastic (12 objects, 36 photos)
${classTable('plastic')}

### Paper (10 objects, 30 photos)
${classTable('paper')}

### Cardboard (10 objects, 30 photos)
${classTable('cardboard')}

### Metal (12 objects, 36 photos)
${classTable('metal')}

### Glass (12 objects, 36 photos)
${classTable('glass')}

### Trash: things that cannot be recycled (10 objects, 30 photos)
${classTable('trash')}

### Biological: food scraps (8 objects, 24 photos)
${classTable('biological')}

Where an item is not available, use a similar object of the same material and keep the same row (location, set and condition).

## 7. Mixed, pile and empty photos

- **Mixed (m001 to m040):** 2 to 4 items from different materials, on a table or the floor. The \`items_needed\` column of the CSV lists which objects to put in the frame (for example \`plastic_o01\`), so use the objects you already photographed alone.
- **Pile (p001 to p020):** 5 to 7 items together in a bag, bin or on the floor, from the same \`items_needed\` list.
- **Empty (n001 to n030):** an empty table (10), floor (10), bin or open bag (5) and outdoor ground (5). These teach the model not to see waste everywhere.

## 8. Train, validation and test split

The split is by **object**, not by photo, so the three shots of one object never end up in different sets. The CSV already has the split for every photo.

| | Plastic, metal, glass (12 objects) | Paper, cardboard, trash (10) | Biological (8) |
|---|---|---|---|
| Train | o01 to o08 | o01 to o07 | o01 to o06 |
| Validation | o09, o10 | o08 | o07 |
| Test | o11, o12 | o09, o10 | o08 |

Mixed and pile photos use only objects from their own split (mixed: m001 to m028 train, m029 to m034 validation, m035 to m040 test; pile: p001 to p014 train, p015 to p017 validation, p018 to p020 test). Empty photos: n001 to n021 train, n022 to n025 validation, n026 to n030 test. Never use test photos for training or augmentation, and never touch them while tuning.

## 9. Labelling

1. **Tool:** Label Studio on your own computer (\`pip install label-studio\`) keeps the photos local. CVAT and Roboflow work too but upload the photos to their servers.
2. **Labels:** create exactly these 7, in this order (the model's contract depends on it): \`metal, trash, glass, paper, cardboard, plastic, biological\`.
3. **Boxes:** draw a tight box around each item and choose its label. Label by material, not by condition (a greasy pizza box is cardboard). Box an item if more than about half is visible; skip tiny or blurry ones. Empty photos get no boxes.
4. **Faster:** for single-item photos the class is in the file name, so an AI detector (Grounding DINO or OWLv2) can draw only the box and take the label from the name. Mixed and pile photos need you to choose each material. Check every automatic box.
5. **Export:** YOLO format, one \`.txt\` per photo (\`class x_center y_center width height\`, values 0 to 1, an empty file for empty photos).
6. **Check:** every photo has a \`.txt\`; class numbers are only 0 to 6; the number of boxes in each photo matches \`expected_boxes\` in the CSV; draw the boxes on about 20 random photos and look at them; re-check about 10% of your labels a day later.

## 10. Checklist

- [ ] ${rows.length} photos named as in the CSV, none duplicated, all in \`ml/data/photos/raw/\`.
- [ ] No faces, plates, addresses or personal text; no hazardous items.
- [ ] Every row of your copy of the CSV is ticked \`done\`.
- [ ] Labels exported as YOLO, 7 classes in the fixed order, box counts match the CSV.
- [ ] Photos are split by object using the \`split\` column; test photos are kept aside.

## 11. After collecting

- **First, a fair comparison:** run the live model (\`v0\`) on the test photos and record its result. Today the accuracy shown on the Models page comes from the public dataset, not from real photos like yours.
- **Then train a candidate:** fine-tune on the public dataset plus your train and validation photos, with augmentation applied during training (not pre-made copies), and release it through the normal flow as a candidate (\`v1\`, 0% rollout). Compare it with \`v0\` on the same test photos before pressing Use. The bundled \`v0\` is never overwritten.
- The retraining notebook does not yet start from \`v0\` or weight your photos more heavily; that would be a change to \`ml/notebooks/kaggle_waste_detector_retraining.ipynb\`.
`;
writeFileSync(path.join(root, 'docs/DATASET_COLLECTION.md'), doc);
console.log(`${doc.split('\n').length} lines written to docs/DATASET_COLLECTION.md`);

function edit(f, fn) {
  const file = path.join(root, f);
  const raw = readFileSync(file, 'utf8');
  const crlf = raw.includes('\r\n');
  const s = raw.replace(/\r\n/g, '\n');
  const t = fn(s);
  if (t !== s) writeFileSync(file, crlf ? t.replace(/\n/g, '\r\n') : t);
}
edit('docs/README.md', (s) => (s.includes('DATASET_COLLECTION') ? s : s.replace('| [ENVIRONMENT.md]', '| [DATASET_COLLECTION.md](./DATASET_COLLECTION.md) | How to photograph and label your own training set, with the full shot list ([dataset/shot_list.csv](./dataset/shot_list.csv)) |\n| [ENVIRONMENT.md]')));
edit('ml/README.md', (s) => (s.includes('DATASET_COLLECTION') ? s : s.replace('- How the whole flow works:', '- Collecting and labelling your own photos: [../docs/DATASET_COLLECTION.md](../docs/DATASET_COLLECTION.md)\n- How the whole flow works:')));
